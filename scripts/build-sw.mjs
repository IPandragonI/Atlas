// Post-build: writes out/sw.js with a precache list generated from the static export.
// Strategy: precache everything (shell, JS/CSS, countries, geometry, graph, daily JSON, flags),
// cache-first for assets, network-first (cache fallback) for navigations.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../out");
if (!fs.existsSync(out)) throw new Error("out/ not found: run `next build` first");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}
const files = walk(out)
  .map((p) => path.relative(out, p).split(path.sep).join("/"))
  .filter((f) => f !== "sw.js" && !f.endsWith(".map") && !f.endsWith(".txt") && !f.startsWith("_next/static/chunks/") || /\.(js|css)$/.test(f))
  .filter((f) => f !== "sw.js" && !f.endsWith(".map"));

const urls = new Set();
for (const f of files) {
  if (f.endsWith("/index.html")) urls.add("/" + f.slice(0, -"index.html".length));
  else if (f === "index.html") urls.add("/");
  else if (f.endsWith(".html")) urls.add("/" + f);
  else urls.add("/" + f);
}
const list = [...urls].sort();
const hash = crypto.createHash("sha1");
for (const f of files) hash.update(f + fs.statSync(path.join(out, f)).size);
const version = hash.digest("hex").slice(0, 10);

const sw = `/* Atlas service worker — generated by scripts/build-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = "atlas-" + VERSION;
const PRECACHE = ${JSON.stringify(list)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // Tolerate individual failures so one missing file never blocks installation.
      await Promise.all(PRECACHE.map((u) => cache.add(u).catch(() => undefined)));
    }),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("atlas-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => undefined);
          return res;
        })
        .catch(async () => {
          const cache = await caches.open(CACHE);
          return (
            (await cache.match(req, { ignoreSearch: true })) ||
            (await cache.match(url.pathname.endsWith("/") ? url.pathname : url.pathname + "/", { ignoreSearch: true })) ||
            (await cache.match("/fr/")) ||
            Response.error()
          );
        }),
    );
    return;
  }

  // Daily JSON: cache-first, so every published day keeps working offline once seen.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => undefined);
          }
          return res;
        }),
    ),
  );
});
`;
fs.writeFileSync(path.join(out, "sw.js"), sw);
console.log(`sw.js written: ${list.length} precached URLs, version ${version}`);
